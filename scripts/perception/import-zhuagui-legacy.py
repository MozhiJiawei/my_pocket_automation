"""Extract all historical ZhuaGui recognition data without executing old actions."""
from pathlib import Path
import hashlib
from lupa import LuaRuntime

ROOT = Path(__file__).resolve().parents[2]


def extract():
    source = ROOT / '参考代码/zhuagui.lua'
    text = source.read_text(encoding='utf-8')
    items = text[text.index('local bb = {}'):text.index('function XunWu')]
    puzzle = text[text.index('\ttt["鼎1"]'):text.index('\n\tlocal name = nil', text.index('function ZhuaGuiPintu'))]
    body = ('-- Historical recognition data, Apache-2.0; see 参考代码/LICENSE.\n'
            '-- Upstream: wanghengxn/mhxy @ 8b03dd6fc12531534bdf82fda10761740fd8517d\n'
            '-- Source SHA256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
            '-- Generated by scripts/perception/import-zhuagui-legacy.py; no legacy actions included.\n'
            + items + '\nlocal tt = {}\n' + puzzle
            + '\nreturn {width=480,height=800,targets=bb,items=cc,puzzles=tt,slots=mm}\n')
    lua = LuaRuntime(unpack_returned_tuples=True)
    data = lua.execute(body)
    stats = {'targets': len(list(data['targets'].keys())),
             'item_categories': len(list(data['items'].keys())),
             'item_features': sum(len(v) for v in data['items'].values()),
             'puzzle_families': len(list(data['puzzles'].keys())),
             'puzzle_features': sum(len(v) for v in data['puzzles'].values())}
    target = ROOT / 'src/tasks/zhuagui/assets/legacy.lua'
    target.write_text(body, encoding='utf-8', newline='\n')
    print(stats)


if __name__ == '__main__':
    extract()
